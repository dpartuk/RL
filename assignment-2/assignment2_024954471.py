UP, DOWN, LEFT, RIGHT = 0, 1, 2, 3
ACTION_DELTAS = {UP: (-1, 0), DOWN: (1, 0), LEFT: (0, -1), RIGHT: (0, 1)}
PERPENDICULAR = {
    UP: [LEFT, RIGHT],
    DOWN: [LEFT, RIGHT],
    LEFT: [UP, DOWN],
    RIGHT: [UP, DOWN],
}


class CustomEnvironment:
    """
    Stochastic Treasure Hunt GridWorld (6x6).

    The agent starts at (0,0) and must reach the treasure at (5,5).
    Walls block movement; traps end the episode with negative reward.
    Transitions are stochastic: 80% intended direction, 10% each perpendicular.

    Layout:
        S  .  .  W  .  .
        .  W  .  .  .  T
        .  .  .  .  .  .
        .  .  W  .  .  .
        .  T  .  .  W  .
        .  .  .  .  .  G

    S=Start, G=Goal(+10), W=Wall, T=Trap(-5), .=Empty(-0.1 step cost)
    """

    ROWS, COLS = 6, 6
    START = (0, 0)
    GOAL = (5, 5)
    WALLS = frozenset({(0, 3), (1, 1), (3, 2), (4, 4)})
    TRAPS = frozenset({(1, 5), (4, 1)})
    STEP_REWARD = -0.1
    GOAL_REWARD = 10.0
    TRAP_REWARD = -5.0
    SLIP_PROB = 0.8

    def __init__(self):
        self.states = [
            (r, c)
            for r in range(self.ROWS)
            for c in range(self.COLS)
            if (r, c) not in self.WALLS
        ]
        self.actions = [UP, DOWN, LEFT, RIGHT]
        self.terminal_states = self.TRAPS | {self.GOAL}
        self.current_state = None

    def reset(self):
        self.current_state = self.START
        return self.current_state

    def _move(self, state, action):
        dr, dc = ACTION_DELTAS[action]
        nr, nc = state[0] + dr, state[1] + dc
        if 0 <= nr < self.ROWS and 0 <= nc < self.COLS and (nr, nc) not in self.WALLS:
            return (nr, nc)
        return state

    def _get_reward(self, next_state):
        if next_state == self.GOAL:
            return self.GOAL_REWARD
        if next_state in self.TRAPS:
            return self.TRAP_REWARD
        return self.STEP_REWARD

    def step(self, action):
        state = self.current_state
        rand_val = random.random()
        if rand_val < self.SLIP_PROB:
            next_state = self._move(state, action)
        elif rand_val < self.SLIP_PROB + 0.1:
            next_state = self._move(state, PERPENDICULAR[action][0])
        else:
            next_state = self._move(state, PERPENDICULAR[action][1])

        reward = self._get_reward(next_state)
        done = next_state in self.terminal_states
        self.current_state = next_state
        return next_state, reward, done, {}

    def get_states(self):
        return list(self.states)

    def get_actions(self, state):
        if state in self.terminal_states:
            return []
        return list(self.actions)

    def get_transition_model(self):
        """
        Return transition model for Dynamic Programming.
        Format: model[state][action] = [(probability, next_state, reward, done), ...]
        """
        model = {}
        for state in self.states:
            if state in self.terminal_states:
                continue
            model[state] = {}
            for action in self.actions:
                transitions = []
                ns = self._move(state, action)
                transitions.append(
                    (self.SLIP_PROB, ns, self._get_reward(ns), ns in self.terminal_states)
                )
                for perp in PERPENDICULAR[action]:
                    ns_p = self._move(state, perp)
                    transitions.append(
                        (0.1, ns_p, self._get_reward(ns_p), ns_p in self.terminal_states)
                    )
                model[state][action] = transitions
        return model


