def epsilon_greedy_action(Q, env, state, epsilon):
    """Choose an action using epsilon-greedy policy with random tie-breaking."""
    actions = env.get_actions(state)
    if not actions:
        return None
    if random.random() < epsilon:
        return random.choice(actions)
    q_values = [Q[(state, a)] for a in actions]
    max_q = max(q_values)
    best_actions = [a for a, q in zip(actions, q_values) if abs(q - max_q) < 1e-10]
    return random.choice(best_actions)


def greedy_policy_from_Q(Q, env):
    """Return deterministic greedy policy from Q."""
    policy = {}
    for state in env.get_states():
        actions = env.get_actions(state)
        if len(actions) == 0:
            continue
        policy[state] = max(actions, key=lambda a: Q[(state, a)])
    return policy


def evaluate_policy(env, policy, episodes=100, max_steps=200, gamma=0.9):
    """Return average discounted return of a policy."""
    returns = []
    for _ in range(episodes):
        state = env.reset()
        G = 0.0
        discount = 1.0
        for _ in range(max_steps):
            action = policy.get(state, None)
            if action is None:
                actions = env.get_actions(state)
                if not actions:
                    break
                action = random.choice(actions)
            next_state, reward, done, info = env.step(action)
            G += discount * reward
            discount *= gamma
            state = next_state
            if done:
                break
        returns.append(G)
    return float(np.mean(returns)) if returns else 0.0


def smooth_rewards(rewards, window=50):
    """Moving average smoothing for plotting."""
    if len(rewards) < window:
        return np.array(rewards)
    return np.convolve(rewards, np.ones(window) / window, mode="valid")


def estimate_convergence(rewards, window=50):
    """Estimate convergence episode: first episode where smoothed reward is within 10% of final avg."""
    smoothed = smooth_rewards(rewards, window)
    if len(smoothed) < window:
        return len(rewards)
    final_avg = np.mean(smoothed[-window:])
    threshold = max(abs(final_avg) * 0.1, 0.5)
    for i, val in enumerate(smoothed):
        if abs(val - final_avg) < threshold:
            return i + window
    return len(rewards)


