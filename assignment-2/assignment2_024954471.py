def run_dynamic_programming(env, gamma=0.9, theta=1e-6, max_iterations=10000):
    """
    Value Iteration: compute optimal V and derive greedy policy.
    Return a dict with keys: V, policy, episodes_rewards, runtime.
    """
    start_time = time.time()
    model = env.get_transition_model()
    states = env.get_states()
    V = {s: 0.0 for s in states}

    for _ in range(max_iterations):
        delta = 0.0
        for state in states:
            actions = env.get_actions(state)
            if not actions:
                continue
            old_v = V[state]
            V[state] = max(
                sum(
                    p * (r + (0.0 if d else gamma * V[ns]))
                    for p, ns, r, d in model[state][a]
                )
                for a in actions
            )
            delta = max(delta, abs(V[state] - old_v))
        if delta < theta:
            break

    policy = {}
    for state in states:
        actions = env.get_actions(state)
        if not actions:
            continue
        policy[state] = max(
            actions,
            key=lambda a: sum(
                p * (r + (0.0 if d else gamma * V[ns]))
                for p, ns, r, d in model[state][a]
            ),
        )

    episodes_rewards = []
    for _ in range(CONFIG["num_episodes"]):
        state = env.reset()
        ep_reward = 0.0
        for _ in range(CONFIG["max_steps_per_episode"]):
            action = policy.get(state)
            if action is None:
                break
            state, reward, done, _ = env.step(action)
            ep_reward += reward
            if done:
                break
        episodes_rewards.append(ep_reward)

    runtime = time.time() - start_time
    return {"V": V, "policy": policy, "episodes_rewards": episodes_rewards, "runtime": runtime}


def run_monte_carlo(env, gamma=0.9, epsilon=0.1, num_episodes=1000, max_steps=200):
    """
    First-visit Monte Carlo control with constant-alpha updates and epsilon-greedy policy.
    Uses incremental Q updates (alpha step size) instead of simple averaging,
    which tracks the improving policy better during on-policy control.
    Return a dict with keys: Q or V, policy, episodes_rewards, runtime.
    """
    start_time = time.time()
    Q = defaultdict(float)
    alpha = CONFIG["alpha"]
    episodes_rewards = []

    for _ in range(num_episodes):
        state = env.reset()
        episode = []
        ep_reward = 0.0

        for _ in range(max_steps):
            action = epsilon_greedy_action(Q, env, state, epsilon)
            next_state, reward, done, _ = env.step(action)
            episode.append((state, action, reward))
            ep_reward += reward
            state = next_state
            if done:
                break
        episodes_rewards.append(ep_reward)

        G = 0.0
        visited = set()
        for s, a, r in reversed(episode):
            G = gamma * G + r
            if (s, a) not in visited:
                visited.add((s, a))
                Q[(s, a)] += alpha * (G - Q[(s, a)])

    policy = greedy_policy_from_Q(Q, env)
    runtime = time.time() - start_time
    return {"Q": dict(Q), "policy": policy, "episodes_rewards": episodes_rewards, "runtime": runtime}


def run_td0(env, gamma=0.9, alpha=0.1, num_episodes=1000, max_steps=200):
    """
    TD(0) value prediction with epsilon-greedy behavior policy.
    Uses the transition model to derive actions from V.
    Return a dict with keys: V, policy, episodes_rewards, runtime.
    """
    start_time = time.time()
    V = defaultdict(float)
    model = env.get_transition_model()
    epsilon = CONFIG["epsilon"]
    episodes_rewards = []

    def _best_action(st):
        acts = env.get_actions(st)
        if not acts:
            return None
        return max(
            acts,
            key=lambda a: sum(
                p * (r + (0.0 if d else gamma * V[ns]))
                for p, ns, r, d in model[st][a]
            ),
        )

    for _ in range(num_episodes):
        state = env.reset()
        ep_reward = 0.0
        for _ in range(max_steps):
            actions = env.get_actions(state)
            if not actions:
                break
            if random.random() < epsilon:
                action = random.choice(actions)
            else:
                action = _best_action(state)
            next_state, reward, done, _ = env.step(action)
            td_target = reward + (0.0 if done else gamma * V[next_state])
            V[state] += alpha * (td_target - V[state])
            ep_reward += reward
            state = next_state
            if done:
                break
        episodes_rewards.append(ep_reward)

    policy = {}
    for state in env.get_states():
        action = _best_action(state)
        if action is not None:
            policy[state] = action

    runtime = time.time() - start_time
    return {"V": dict(V), "policy": policy, "episodes_rewards": episodes_rewards, "runtime": runtime}


def run_q_learning(env, gamma=0.9, alpha=0.1, epsilon=0.1, num_episodes=1000, max_steps=200):
    """
    Off-policy Q-Learning with epsilon-greedy exploration.
    Return a dict with keys: Q, policy, episodes_rewards, runtime.
    """
    start_time = time.time()
    Q = defaultdict(float)
    episodes_rewards = []

    for _ in range(num_episodes):
        state = env.reset()
        ep_reward = 0.0
        for _ in range(max_steps):
            action = epsilon_greedy_action(Q, env, state, epsilon)
            next_state, reward, done, _ = env.step(action)
            next_actions = env.get_actions(next_state)
            max_q_next = max((Q[(next_state, a)] for a in next_actions), default=0.0)
            Q[(state, action)] += alpha * (
                reward + gamma * max_q_next - Q[(state, action)]
            )
            ep_reward += reward
            state = next_state
            if done:
                break
        episodes_rewards.append(ep_reward)

    policy = greedy_policy_from_Q(Q, env)
    runtime = time.time() - start_time
    return {"Q": dict(Q), "policy": policy, "episodes_rewards": episodes_rewards, "runtime": runtime}


def run_sarsa(env, gamma=0.9, alpha=0.1, epsilon=0.1, num_episodes=1000, max_steps=200):
    """
    On-policy SARSA with epsilon-greedy policy.
    Return a dict with keys: Q, policy, episodes_rewards, runtime.
    """
    start_time = time.time()
    Q = defaultdict(float)
    episodes_rewards = []

    for _ in range(num_episodes):
        state = env.reset()
        action = epsilon_greedy_action(Q, env, state, epsilon)
        ep_reward = 0.0
        for _ in range(max_steps):
            next_state, reward, done, _ = env.step(action)
            next_actions = env.get_actions(next_state)
            if next_actions:
                next_action = epsilon_greedy_action(Q, env, next_state, epsilon)
                q_next = Q[(next_state, next_action)]
            else:
                next_action = None
                q_next = 0.0
            Q[(state, action)] += alpha * (
                reward + gamma * q_next - Q[(state, action)]
            )
            ep_reward += reward
            if done:
                break
            state = next_state
            action = next_action
        episodes_rewards.append(ep_reward)

    policy = greedy_policy_from_Q(Q, env)
    runtime = time.time() - start_time
    return {"Q": dict(Q), "policy": policy, "episodes_rewards": episodes_rewards, "runtime": runtime}


def run_td_lambda(env, gamma=0.9, alpha=0.1, lam=0.8, num_episodes=1000, max_steps=200):
    """
    SARSA(lambda) with accumulating eligibility traces.
    Return a dict with keys: V or Q, policy, episodes_rewards, runtime.
    """
    start_time = time.time()
    Q = defaultdict(float)
    epsilon = CONFIG["epsilon"]
    episodes_rewards = []

    for _ in range(num_episodes):
        E = defaultdict(float)
        state = env.reset()
        action = epsilon_greedy_action(Q, env, state, epsilon)
        ep_reward = 0.0

        for _ in range(max_steps):
            next_state, reward, done, _ = env.step(action)
            next_actions = env.get_actions(next_state)
            if next_actions:
                next_action = epsilon_greedy_action(Q, env, next_state, epsilon)
                q_next = Q[(next_state, next_action)]
            else:
                next_action = None
                q_next = 0.0

            td_error = reward + gamma * q_next - Q[(state, action)]
            E[(state, action)] += 1.0

            for sa in list(E.keys()):
                Q[sa] += alpha * td_error * E[sa]
                E[sa] *= gamma * lam
                if E[sa] < 1e-10:
                    del E[sa]

            ep_reward += reward
            if done:
                break
            state = next_state
            action = next_action
        episodes_rewards.append(ep_reward)

    policy = greedy_policy_from_Q(Q, env)
    runtime = time.time() - start_time
    return {"Q": dict(Q), "policy": policy, "episodes_rewards": episodes_rewards, "runtime": runtime}


